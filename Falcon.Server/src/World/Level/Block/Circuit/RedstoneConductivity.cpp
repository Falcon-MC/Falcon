RedstoneConductivity RedstoneConductivity::of(const BlockState &state) {
    RedstoneConductivity conductivity;
    const std::string &name = state.mName;
    if (name == "minecraft:glowstone") {
        conductivity.mConductor = true;
        conductivity.mAllowsWireToStepDown = false;
        return conductivity;
    }
    if (name == "minecraft:hopper") {
        conductivity.mAllowsWireToStepDown = false;
        return conductivity;
    }
    conductivity.mConductor = conductors().count(name) != 0;
    if (isDataDriven(name))
        return conductivity;
    // the game's slab and stairs classes take step-down away from a top slab and an upside-down stair
    if (VanillaBlocks::getAs<SlabBlock>(name) != nullptr && SlabBlock::isTopSlab(state))
        conductivity.mAllowsWireToStepDown = false;
    else if (VanillaBlocks::getAs<StairsBlock>(name) != nullptr && state.mStates.getBool("upside_down_bit", false))
        conductivity.mAllowsWireToStepDown = false;
    return conductivity;
}
