#!/usr/bin/env python3
"""Generate src/World/Level/Block/BlockMaterialTable.inc: the game's material and property 0x40000 of every block.

usage: gen_block_materials.py <game data directory> [repository root]

Two sources, nothing typed in by hand:
- tools/BlockMaterials/ida_block_materials.json: the material types and their flags, and the material each
  code-registered block gets in the 26.60 client, each with the address it was read at. An entry with a
  "base" takes the material of that block, as the game's stairs and walls do.
- behavior_packs/*/__brarchive/blocks.brarchive of the installed game: the blocks the game defines in json,
  whose "internal_vanilla_data.material" goes through the game's name -> type map (sub_149948C40), except
  the stair_block archetype, which builds its stairs from the material of "base_block" (sub_14317C7D0).

The property is bit 0x40000 of BlockLegacy +304: set by the base constructor, kept or cleared by each class and
registration. For json blocks it follows the archetype: slabs keep it only when double (sub_148F8BC20), stairs
store 1 (sub_148F9C8D0), bushes and wall foliage store 0 (sub_143170AA0, sub_144A346B0).

Every identifier of BlockData.cpp must get exactly one entry.
"""

import glob
import json
import os
import re
import sys

if len(sys.argv) < 2:
    raise SystemExit(__doc__)
game = sys.argv[1]
root = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')

evidence = json.load(open(os.path.join(root, 'tools/BlockMaterials/ida_block_materials.json')))
types = [entry['name'] for entry in evidence['types']]
blocks = dict(evidence['blocks'])

archives = sorted(glob.glob(os.path.join(game, 'behavior_packs/vanilla*/__brarchive/blocks.brarchive')))
if not archives:
    raise SystemExit('no blocks.brarchive under %s/behavior_packs' % game)
defined = {}
decoder = json.JSONDecoder()
for archive in archives:
    text = open(archive, 'rb').read().decode('utf-8', 'replace')
    for start in [match.start() for match in re.finditer(r'\{"format_version"', text)]:
        document, _ = decoder.raw_decode(text, start)
        description = document['minecraft:block']['description']
        data = description.get('internal_vanilla_data')
        if data is None:
            continue
        archetype = data.get('block_archetype', {})
        if 'stair_block' in archetype:
            entry = {'base': archetype['stair_block']['base_block'], 'property': False}
        else:
            entry = {'type': types.index(data['material'])}
            if 'slab_block' in archetype:
                entry['property'] = archetype['slab_block']['is_double']
            elif 'bush_block' in archetype or 'wall_foliage_block' in archetype:
                entry['property'] = False
            else:
                raise SystemExit('%s: archetype %s not read' % (description['identifier'], list(archetype)))
        defined[description['identifier']] = entry
for identifier, entry in defined.items():
    if identifier in blocks:
        raise SystemExit('%s is read twice' % identifier)
    blocks[identifier] = entry


def resolve(identifier, seen=()):
    entry = blocks.get(identifier)
    if entry is None:
        raise SystemExit('no material for %s' % identifier)
    if 'type' in entry:
        return entry['type']
    if identifier in seen:
        raise SystemExit('base loop at %s' % identifier)
    return resolve(entry['base'], seen + (identifier,))


source = open(os.path.join(root, 'src/World/Level/Block/BlockData.cpp')).read()
identifiers = sorted(set(re.findall(r'\{BlockTypeIds::[A-Z0-9_]+, "(minecraft:[a-z0-9_]+)"', source)))
extra = sorted(set(blocks) - set(identifiers))
if extra:
    raise SystemExit('materials for blocks BlockData.cpp does not have: %s' % ', '.join(extra))

names = {name: ''.join(part.capitalize() for part in name.split('_')) for name in types}
lines = ['// generated by tools/gen_block_materials.py from tools/BlockMaterials and the game\'s blocks.brarchive;',
         '// do not edit',
         'const uint8_t FLAGS[] = {%s};' % ', '.join('0x%02x' % entry['flags'] for entry in evidence['types']),
         '',
         'const Entry ENTRIES[] = {']
for identifier in identifiers:
    lines.append('        {"%s", BlockMaterialType::%s, %s},' % (
        identifier, names[types[resolve(identifier)]], 'true' if blocks[identifier]['property'] else 'false'))
lines.append('};')
target = os.path.join(root, 'src/World/Level/Block/BlockMaterialTable.inc')
open(target, 'w').write('\n'.join(lines) + '\n')
print('%d block materials written' % len(identifiers))
