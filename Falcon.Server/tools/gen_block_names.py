#!/usr/bin/env python3
"""Generate include/World/Level/Block/BlockNames.h from the block table in BlockData.cpp.

usage: gen_block_names.py [repository root]

One constant per block, named like its BlockTypeIds entry, holding its identifier. Run it again whenever
blocks are added to the table.
"""

import os
import re
import sys

root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
source = os.path.join(root, 'src/World/Level/Block/BlockData.cpp')
target = os.path.join(root, 'include/World/Level/Block/BlockNames.h')

names = {}
for constant, identifier in re.findall(r'\{BlockTypeIds::([A-Z0-9_]+), "([a-z0-9_:]+)"', open(source).read()):
    known = names.setdefault(constant, identifier)
    if known != identifier:
        raise SystemExit('%s names both %s and %s' % (constant, known, identifier))

lines = ['// generated by tools/gen_block_names.py from the block table in BlockData.cpp; do not edit',
         '#pragma once',
         '',
         '// every block identifier, named once',
         'namespace BlockNames {']
for constant in sorted(names):
    line = '    inline constexpr const char *const %s = "%s";' % (constant, names[constant])
    if len(line) > 120:
        line = '    inline constexpr const char *const %s =\n            "%s";' % (constant, names[constant])
    lines.append(line)
lines.append('}')
open(target, 'w').write('\n'.join(lines) + '\n')
print('%d block names written' % len(names))
